-- Genererer et øjebliksbillede af det levende public-skema som DDL (kun læsning).
-- Køres af scripts/schema_snapshot.sh. Hver række: (sektion, navn, ddl).
with
fn as (
  select p.oid, p.proname, pg_get_function_identity_arguments(p.oid) args
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
tb as (
  select c.oid, c.relname, c.relrowsecurity, c.relacl
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r','p')
),
rows as (
  -- 01 udvidelser
  select 1 s, extname::text nm, format('create extension if not exists %I with schema %I;', extname, nspname) ddl
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where extname not in ('plpgsql')
  union all
  -- 02 enums
  select 2, t.typname, format('create type public.%I as enum (%s);', t.typname,
         (select string_agg(quote_literal(enumlabel), ', ' order by enumsortorder) from pg_enum where enumtypid = t.oid))
  from pg_type t join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'
  union all
  -- 03 sekvenser (ikke identity)
  select 3, c.relname, format('create sequence if not exists public.%I;', c.relname)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
  union all
  -- 04 tabeller
  select 4, tb.relname, format(E'create table public.%I (\n%s\n);', tb.relname,
    (select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
        case when a.attidentity = 'a' then ' generated always as identity'
             when a.attidentity = 'd' then ' generated by default as identity' else '' end,
        case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
             when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end,
        case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum)
     from pg_attribute a left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
     where a.attrelid = tb.oid and a.attnum > 0 and not a.attisdropped))
  from tb
  union all
  -- 05 primær-, unikke og check-nøgler; 06 fremmednøgler
  select case when co.contype = 'f' then 6 else 5 end, tb.relname || '.' || co.conname,
         format('alter table public.%I add constraint %I %s;', tb.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co join tb on tb.oid = co.conrelid
  where co.contype in ('p','u','c','f','x')
  union all
  -- 07 indeks der ikke hører til en nøgle
  select 7, i.relname, pg_get_indexdef(i.oid) || ';'
  from pg_index x join pg_class i on i.oid = x.indexrelid join tb on tb.oid = x.indrelid
  where not exists (select 1 from pg_constraint co where co.conindid = i.oid)
  union all
  -- 08 views
  select 8, c.relname, format(E'create or replace view public.%I as\n%s', c.relname, pg_get_viewdef(c.oid, true))
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
  union all
  -- 09 funktioner
  select 9, fn.proname || '(' || fn.args || ')', pg_get_functiondef(fn.oid) || ';'
  from fn
  union all
  -- 10 triggere
  select 10, tb.relname || '.' || t.tgname, pg_get_triggerdef(t.oid) || ';'
  from pg_trigger t join tb on tb.oid = t.tgrelid where not t.tgisinternal
  union all
  -- 11 RLS
  select 11, tb.relname, format('alter table public.%I enable row level security;', tb.relname)
  from tb where tb.relrowsecurity
  union all
  -- 12 policies
  select 12, p.tablename || '.' || p.policyname,
    format('create policy %I on public.%I as %s for %s to %s%s%s;', p.policyname, p.tablename, p.permissive, p.cmd,
      array_to_string(p.roles, ', '),
      case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
      case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end)
  from pg_policies p where p.schemaname = 'public'
  union all
  -- 13 tabelrettigheder (kun anon/authenticated/service_role)
  select 13, tb.relname || ':' || r.rolname,
    format('grant %s on public.%I to %I;', string_agg(lower(a.privilege_type), ', ' order by a.privilege_type), tb.relname, r.rolname)
  from tb cross join lateral aclexplode(tb.relacl) a join pg_roles r on r.oid = a.grantee
  where r.rolname in ('anon','authenticated','service_role')
  group by tb.relname, r.rolname
  union all
  -- 14 funktionsrettigheder (hvem må kalde hvad)
  select 14, fn.proname || '(' || fn.args || ')',
    format('revoke all on function public.%I(%s) from public, anon, authenticated;%s', fn.proname, fn.args,
      coalesce((select string_agg(format(' grant execute on function public.%I(%s) to %s;', fn.proname, fn.args,
                 case when a.grantee = 0 then 'public' else quote_ident(r.rolname) end), '' order by r.rolname)
                from pg_proc p cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
                left join pg_roles r on r.oid = a.grantee
                where p.oid = fn.oid and a.privilege_type = 'EXECUTE'
                  and (a.grantee = 0 or r.rolname in ('anon','authenticated','service_role'))), ''))
  from fn
  union all
  -- 15 realtime
  select 15, pt.tablename, format('alter publication supabase_realtime add table public.%I;', pt.tablename)
  from pg_publication_tables pt where pt.pubname = 'supabase_realtime' and pt.schemaname = 'public'
)
select s, nm, ddl from rows order by s, nm;

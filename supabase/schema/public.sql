  if turn_user(g) is distinct from auth.uid() then raise exception 'It''s not your turn'; end if;
  if g.current_club is null then raise exception 'Spin the wheel first'; end if;
  if exists (select 1 from game_players where game_id = p_game and user_id = auth.uid() and respins_used >= g.respins) then raise exception 'You''ve used your respins'; end if;
  select club into c from _clubs_for(p_game, auth.uid()) club where club <> g.current_club order by random() limit 1;
  if c is null then raise exception 'No other club has a usable player'; end if;
  update game_players set respins_used = respins_used + 1, last_seen_at = now() where game_id = p_game and user_id = auth.uid();
  update games set current_club = c,
    turn_deadline = case when timer_seconds > 0 then now() + make_interval(secs => timer_seconds + 4) end
  where id = p_game;
  return c;
end $function$
;

CREATE OR REPLACE FUNCTION public.rls_auto_enable()
 RETURNS event_trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  cmd record;
  tbl name;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        SELECT c.relname INTO tbl FROM pg_catalog.pg_class c WHERE c.oid = cmd.objid;
        EXECUTE format('alter table if exists %I.%I enable row level security', cmd.schema_name, tbl);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$function$
;


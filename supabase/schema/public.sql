CREATE OR REPLACE FUNCTION public._begin_draft(p_game uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare g games; ord uuid[];
begin
  select * into g from games where id = p_game for update;
  select array_agg(user_id order by random()) into ord from game_players where game_id = p_game;
  update game_players gp set draft_pos = x.n from unnest(ord) with ordinality as x(u, n) where gp.game_id = p_game and gp.user_id = x.u;
  update games set status = 'draft', draft_order = ord, current_pick = 0, current_club = null,
    turn_deadline = case when timer_seconds > 0 then now() + make_interval(secs => least(timer_seconds, 20) + 8 + coalesce(array_length(ord, 1), 1)) end
  where id = p_game;
end $function$
;

CREATE OR REPLACE FUNCTION public._best_pick(p_game uuid, p_user uuid, p_club text)
 RETURNS TABLE(player_id integer, slot integer)
 LANGUAGE sql
 SET search_path TO 'public'
AS $function$
  with cand as (
    select pl.id as pid, s.i::int as sl,
           pl.rating * case when pfit(pl.pos, pl.alts, s.pos) = 2 then 1.0 else 0.90 end as score,
           (pfit(pl.pos, pl.alts, s.pos) = 2) as exact
    from players pl
    join game_players gp on gp.game_id = p_game and gp.user_id = p_user
    cross join lateral unnest(formation_slots(gp.formation)) with ordinality s(pos, i)
    where pl.club = p_club
      and not exists (select 1 from draft_picks dp where dp.game_id = p_game and dp.user_id = p_user and dp.slot = s.i)
      and not exists (select 1 from draft_picks dp where dp.game_id = p_game and dp.player_id = pl.id)
      and pfit(pl.pos, pl.alts, s.pos) > 0
  ), best as (
    select distinct on (pid) pid, sl, score from cand order by pid, score desc, exact desc, sl asc
  ), top3 as (
    select pid, sl from best order by score desc, pid asc limit 3
  )
  select pid, sl from top3 order by random() limit 1
$function$
;

CREATE OR REPLACE FUNCTION public._check_manager_name(p text)
 RETURNS text
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare n text := _clean_name(p);
begin
  if length(n) not between 2 and 16 then raise exception 'Your manager name must be 2 to 16 characters'; end if;
  if n ~ '[<>]' then raise exception 'Names can''t contain < or >'; end if;
  if exists (select 1 from profiles where lower(manager_name) = lower(n) and user_id <> auth.uid()) then raise exception 'That manager name is taken'; end if;
  return n;
end $function$
;


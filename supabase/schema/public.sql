 RETURNS uuid
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
  select g.draft_order[
    1 + case when (g.current_pick / array_length(g.draft_order, 1)) % 2 = 1
             then array_length(g.draft_order, 1) - 1 - (g.current_pick % array_length(g.draft_order, 1))

    when (p_pos, p_slot) in (('LB','RB'),('RB','LB'),('DM','CM'),('CM','DM'),('CM','AM'),('AM','CM'),('LW','ST'),('RW','ST'),('ST','LW'),('ST','RW'),('LW','RW'),('RW','LW'),
      ('LB','LWB'),('RB','RWB'),('LWB','LB'),('RWB','RB'),('LWB','LM'),('LWB','LW'),('RWB','RM'),('RWB','RW')) then 1
    else 0 end
$function$

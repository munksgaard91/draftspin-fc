CREATE OR REPLACE FUNCTION public._spin(g games)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare c text;
begin
  select club into c from _clubs_for(g.id, turn_user(g)) club order by random() limit 1;
  if c is null then raise exception 'No club has a usable player'; end if;
  update games set current_club = c,
    turn_deadline = case when timer_seconds > 0 then now() + make_interval(secs => timer_seconds + 4) end
  where id = g.id;
  return c;
end $function$
;

